def mname(lang: str, m: int) -> str:
    names = MONTH_NAMES.get(lang) or MONTH_NAMES["en"]
    return names[m - 1]


def t(lang: str, key: str, **kw) -> str:
    s = T[lang].get(key) or T["en"][key]
    if "y" in kw and "m" in kw and "mname" not in kw:
        kw["mname"] = mname(lang, kw["m"])
    return s.format(**kw) if kw else s


